const branchId = 'branch-main', clock = () => new Date('2026-10-10T12:00:00+05:00')
const customerInput = changes => ({ branchId, operationId: randomUUID(), name: 'Accounts Customer', phone: '03001234567', openingBalancePaisa: 10000, ...changes })
const paymentInput = (customerId, changes) => ({ branchId, operationId: randomUUID(), customerId, amountPaisa: 5000, method: 'Cash', reference: '', ...changes })
const expenseInput = changes => ({ branchId, operationId: randomUUID(), businessDate: '2026-10-10', description: 'Shop electricity', category: 'Utilities', amountPaisa: 5000, method: 'Cash', reference: '', ...changes })
const expenseQuery = changes => ({ branchId, dateFrom: '2026-10-01', dateTo: '2026-10-10', search: '', category: '', method: '', page: 1, pageSize: 25, ...changes })
const customerQuery = changes => ({ branchId, search: '', filter: 'all', page: 1, pageSize: 25, ...changes })
const counts = db => ['customers','customer_ledger','customer_receipts','expenses','expense_postings','expense_reversals','cash_transactions','audit_events','operation_results','account_document_sequences'].map(table => db.connection.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n)
function setup(t, now = clock) {
  const db = new VertexiaDatabase(':memory:', now)
  t.after(() => db.close())
  return db
}

test('opening debt is auditable, retry-safe and branch scoped, with no invented sales or cash', t => {
  const db = setup(t), request = customerInput(), result = db.accounts.createCustomer(request)
  assert.deepEqual(db.accounts.createCustomer(request), result)
  const detail = db.accounts.customerDetail(branchId, result.customerId)
  assert.equal(detail.customer.balancePaisa, 10000); assert.equal(detail.customer.creditSalesPaisa, 0)
  assert.equal(detail.ledger[0].type, 'opening_balance')
  assert.equal(db.accounts.customers(customerQuery()).duePaisa, 10000)
  assert.equal(db.connection.prepare('SELECT COUNT(*) AS n FROM sales').get().n, 0)
  assert.equal(db.connection.prepare('SELECT COUNT(*) AS n FROM cash_transactions').get().n, 0)
  assert.throws(() => db.accounts.createCustomer({ ...request, openingBalancePaisa: 1 }), /different request/)
  const before = counts(db)
  for (const value of [-1, 0.5, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => db.accounts.createCustomer(customerInput({ openingBalancePaisa: value })), /safe integer/)
  assert.throws(() => db.accounts.createCustomer(customerInput({ branchId: 'missing' })), /unavailable/)
  assert.throws(() => db.accounts.createCustomer(customerInput({ operationId: undefined })), /Operation identifier/)
  assert.deepEqual(counts(db), before)
})

test('udhaar sale, collections and return share the account while revenue and drawer remain separate', t => {
  const db = setup(t), { customerId } = db.accounts.createCustomer(customerInput({ openingBalancePaisa: 0 }))
  const shiftId = db.openPosShift(branchId, 100000)
  const product = db.saveProduct(branchId, { name: 'Account Rice', sku: 'AC-001', barcode: 'AC-001', category: 'General', subcategory: '', brand: '', unit: 'Kg', purchasePricePaisa: 10000, sellingPricePaisa: 15000, mrpPaisa: 0, minimumStockMilli: 0, openingStockMilli: 5000, status: 'active', imageDataUrl: null })
  const sale = db.completePosSale({ branchId, operationId: randomUUID(), customerId, paymentMethod: 'Udhaar', cashReceivedPaisa: 0, lines: [{ productId: product.id, quantityMilli: 2000, discountBasisPoints: 0 }] })
  const receipt = db.accounts.collect(paymentInput(customerId, { amountPaisa: 10000 }))
  assert.equal(receipt.balanceAfterPaisa, 20000); assert.equal(db.cash.expected(shiftId), 110000)
  db.accounts.collect(paymentInput(customerId, { amountPaisa: 5000, method: 'Card', reference: 'CARD-0001' }))
  assert.equal(db.cash.expected(shiftId), 110000)
  let dashboard = db.getDashboardSnapshot({ branchId, dateRange: 'today', chartPeriod: 'today' })
  assert.equal(dashboard.salesPaisa, 30000); assert.equal(dashboard.profitPaisa, 10000); assert.equal(dashboard.customerDuePaisa, 15000)
  const item = db.getSalesDetail(branchId, sale.saleId).lines[0]
  db.createSalesReturn({ branchId, operationId: randomUUID(), saleId: sale.saleId, reason: 'One bag returned', lines: [{ saleItemId: item.id, quantityMilli: 1000 }] })
  const detail = db.accounts.customerDetail(branchId, customerId)
  assert.equal(detail.customer.balancePaisa, 0); assert.equal(detail.customer.creditSalesPaisa, 30000); assert.equal(detail.customer.collectedPaisa, 15000); assert.equal(detail.customer.returnsPaisa, 15000)
  assert.equal(detail.ledger[0].balanceAfterPaisa, 0); assert.equal(detail.receipts.length, 2); assert.equal(detail.sales.length, 1)
  dashboard = db.getDashboardSnapshot({ branchId, dateRange: 'today', chartPeriod: 'today' })
  assert.equal(dashboard.customerDuePaisa, 0); assert.equal(db.cash.expected(shiftId), 110000)
})

