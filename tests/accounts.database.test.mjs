test('cashier permissions, shift ownership and retry namespace protect collections; manager controls expenses', async t => {
  const db = setup(t), auth = new AuthRepository(db.connection)
  await auth.setup({ businessName: 'Account Shop', branchName: 'Main', city: 'Karachi', ownerName: 'Owner', username: 'owner', password: 'Owner account password 2026' })
  await auth.createUser({ name: 'Cashier', username: 'cashier', password: 'Cashier temp password 2026', role: 'Cashier', branchIds: [branchId] })
  const { customerId } = db.accounts.createCustomer(customerInput()), ownerShift = db.openPosShift(branchId, 0)
  auth.logout(); await auth.login('cashier', 'Cashier temp password 2026'); await auth.changePassword('Cashier temp password 2026', 'Cashier own password 2026')
  authorizeIpc(auth, db, 'customers:list', [customerQuery()])
  assert.throws(() => authorizeIpc(auth, db, 'customers:collect', [paymentInput(customerId)]), /own open shift/)
  authorizeIpc(auth, db, 'customers:collect', [paymentInput(customerId, { method: 'Card', reference: 'CARD' })])
  assert.throws(() => authorizeIpc(auth, db, 'customers:create', [customerInput()]), /permission/)
  authorizeIpc(auth, db, 'customers:create', [customerInput({ openingBalancePaisa: 0 })])
  for (const channel of ['customers:update','expenses:list','expenses:post','expenses:reverse']) assert.throws(() => authorizeIpc(auth, db, channel, [{ branchId }]), /permission/)
  assert.throws(() => authorizeIpc(auth, db, 'customers:detail', ['forbidden', customerId]), /branch/)
  auth.logout(); await auth.login('owner', 'Owner account password 2026')
  authorizeIpc(auth, db, 'cash:close-shift', [{ branchId, shiftId: ownerShift }]); db.cash.close({ branchId, operationId: randomUUID(), shiftId: ownerShift, countedCashPaisa: 0, note: '' })
  const cashier = auth.listUsers().find(user => user.username === 'cashier')
  auth.logout(); await auth.login('cashier', 'Cashier own password 2026')
  authorizeIpc(auth, db, 'pos:open-shift', [branchId, 0]); db.openPosShift(branchId, 0)
  const ownPayment = paymentInput(customerId)
  authorizeIpc(auth, db, 'customers:collect', [ownPayment])
  const ownReceipt = db.accounts.collect(ownPayment)
  assert.equal(ownReceipt.receivedBy, 'Cashier'); assert.equal(ownReceipt.balanceAfterPaisa, 5000)
  auth.logout(); await auth.login('owner', 'Owner account password 2026')
  await auth.updateUser({ userId: cashier.id, name: 'Cashier', role: 'Manager', branchIds: [branchId], isActive: true })
  auth.logout(); await auth.login('cashier', 'Cashier own password 2026')
  authorizeIpc(auth, db, 'expenses:post', [expenseInput({ method: 'Card', reference: 'CARD-MANAGER' })])
  db.accounts.postExpense(expenseInput({ method: 'Card', reference: 'CARD-MANAGER' }))
  const raw = randomUUID(), args = [paymentInput(customerId, { operationId: raw })]
  scopeOperation('customers:collect', args, cashier.id)
  assert.notEqual(args[0].operationId, raw)
  const otherArgs = [paymentInput(customerId, { operationId: raw })]; scopeOperation('customers:collect', otherArgs, 'another-user')
  assert.notEqual(otherArgs[0].operationId, args[0].operationId)
})
