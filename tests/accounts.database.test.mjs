test('durable retry results survive restart and changed input cannot reuse an operation', t => {
  const directory = mkdtempSync(join(tmpdir(), 'vertexia-accounts-')), path = join(directory, 'store.db')
  let db = new VertexiaDatabase(path, clock)
  t.after(() => { db.close(); rmSync(directory, { recursive: true, force: true }) })
  const create = customerInput(), customer = db.accounts.createCustomer(create)
  db.openPosShift(branchId, 100000)
  const collect = paymentInput(customer.customerId), receipt = db.accounts.collect(collect)
  const post = expenseInput(), expense = db.accounts.postExpense(post)
  const reverse = { branchId, operationId: randomUUID(), expenseId: expense.expenseId, reason: 'Wrong expense entered' }, reversal = db.accounts.reverseExpense(reverse), before = counts(db)
  db.close(); db = new VertexiaDatabase(path, clock)
  assert.deepEqual(db.accounts.createCustomer(create), customer); assert.deepEqual(db.accounts.collect(collect), receipt)
  assert.deepEqual(db.accounts.postExpense(post), expense); assert.deepEqual(db.accounts.reverseExpense(reverse), reversal)
  assert.deepEqual(counts(db), before)
  assert.throws(() => db.accounts.collect({ ...collect, amountPaisa: 1 }), /different request/)
  assert.throws(() => db.accounts.postExpense({ ...post, category: 'Rent' }), /different request/)
  assert.throws(() => db.accounts.reverseExpense({ ...reverse, reason: 'Different reason' }), /different request/)
})

