test('cash expenses reduce drawer; bank expenses do not; invalid postings are fully rejected', t => {
  const db = setup(t), before = counts(db)
  assert.throws(() => db.accounts.postExpense(expenseInput()), /Open a cash shift/)
  assert.deepEqual(counts(db), before)
  const shiftId = db.openPosShift(branchId, 10000)
  db.accounts.postExpense(expenseInput())
  db.accounts.postExpense(expenseInput({ amountPaisa: 2000, method: 'Bank Transfer', reference: 'BANK-EXPENSE' }))
  assert.equal(db.cash.expected(shiftId), 5000)
  const snapshot = db.accounts.expenses(expenseQuery())
  assert.equal(snapshot.netPaisa, 7000); assert.equal(snapshot.postedPaisa, 7000); assert.equal(snapshot.reversedPaisa, 0)
  assert.equal(db.getDashboardSnapshot({ branchId, dateRange: 'today', chartPeriod: 'today' }).expensesPaisa, 7000)
  const after = counts(db)
  assert.throws(() => db.accounts.postExpense(expenseInput({ amountPaisa: 5001 })), /available drawer cash/)
  for (const amountPaisa of [0, -1, 1.2, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => db.accounts.postExpense(expenseInput({ amountPaisa })), /safe integer/)
  assert.throws(() => db.accounts.postExpense(expenseInput({ businessDate: '2026-10-11' })), /future/)
  assert.throws(() => db.accounts.postExpense(expenseInput({ businessDate: '2026-02-30' })), /valid purchase date/)
  assert.throws(() => db.accounts.postExpense(expenseInput({ method: 'Card' })), /transaction reference/)
  assert.deepEqual(counts(db), after)
})

test('expense reversal preserves original and uses current date/current drawer across closed shifts', t => {
  let time = clock()
  const db = setup(t, () => time), shiftId = db.openPosShift(branchId, 10000), original = db.accounts.postExpense(expenseInput())
  db.cash.close({ branchId, operationId: randomUUID(), shiftId, countedCashPaisa: 5000, note: '' })
  const request = { branchId, operationId: randomUUID(), expenseId: original.expenseId, reason: 'Expense refunded by vendor' }
  const before = counts(db)
  assert.throws(() => db.accounts.reverseExpense(request), /Open a cash shift/)
  assert.deepEqual(counts(db), before)
  time = new Date('2026-10-11T12:00:00+05:00')
  const nextShift = db.openPosShift(branchId, 1000)
  const result = db.accounts.reverseExpense(request)
  assert.equal(result.number, 'REV-20261011-0001'); assert.equal(db.cash.expected(nextShift), 6000)
  assert.equal(db.cash.snapshot(branchId).shifts[1].expectedCashPaisa, 5000)
  assert.equal(db.accounts.expenses(expenseQuery()).netPaisa, 5000)
  assert.equal(db.accounts.expenses(expenseQuery({ dateFrom: '2026-10-11', dateTo: '2026-10-11' })).netPaisa, -5000)
  assert.equal(db.getDashboardSnapshot({ branchId, dateRange: 'today', chartPeriod: 'today' }).expensesPaisa, -5000)
  const all = db.accounts.expenses(expenseQuery({ dateTo: '2026-10-11' }))
  assert.equal(all.netPaisa, 0); assert.equal(all.records.length, 2); assert.ok(all.records.every(row => row.isReversed))
  assert.equal(db.connection.prepare('SELECT amount_paisa FROM expenses WHERE id=?').get(original.expenseId).amount_paisa, 5000)
  assert.throws(() => db.accounts.reverseExpense({ ...request, operationId: randomUUID() }), /already been reversed/)
})

