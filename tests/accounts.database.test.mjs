test('failed audit rolls back customer payment, expenses and document numbering atomically', t => {
  const db = setup(t), { customerId } = db.accounts.createCustomer(customerInput())
  db.openPosShift(branchId, 100000)
  db.connection.exec("CREATE TRIGGER reject_account_audit BEFORE INSERT ON audit_events BEGIN SELECT RAISE(ABORT,'Injected audit failure'); END")
  const before = counts(db)
  assert.throws(() => db.accounts.collect(paymentInput(customerId)), /Injected audit failure/)
  assert.throws(() => db.accounts.postExpense(expenseInput()), /Injected audit failure/)
  assert.deepEqual(counts(db), before)
  assert.equal(db.accounts.customerDetail(branchId, customerId).customer.balancePaisa, 10000)
  db.connection.exec('DROP TRIGGER reject_account_audit')
  assert.equal(db.accounts.collect(paymentInput(customerId)).number, 'REC-20261010-0001')
  assert.equal(db.accounts.postExpense(expenseInput()).number, 'EXP-20261010-0001')
})

